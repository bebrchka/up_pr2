List<String> brandCountries() {
  final countries = <String>{};
  for (final brand in seedBrands) {
    countries.add(brand.country);
  }
  final result = countries.toList()..sort();
  return result;
}

String brandNameOf(int id) {
  for (final brand in seedBrands) {
    if (brand.id == id) return brand.name;
  }
  return 'Бренд #$id';
}

String categoryNameOf(int id) {
  for (final category in seedCategories) {
    if (category.id == id) return category.name;
  }
  return 'Категория #$id';
}

String categoryNamesOf(List<int> ids) => ids.map(categoryNameOf).join(', ');
